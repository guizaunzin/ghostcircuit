// Map tooling.
//   npm run gen:map -- scan 1 50     evaluate seeds (autopilot laps, shortcut gain)
//   npm run gen:map -- show 16       print the TrackDef for one seed
//   npm run gen:maps                 bake scripts/map-seeds.ts into src/game/generatedMaps.ts
import { writeFileSync } from 'node:fs';
import { generateTrackDef } from '../src/game/generator';
import { buildTrack, type TrackDef } from '../src/game/track';
import { autopilotLap } from './eval-map';
import { MAP_SEEDS } from './map-seeds';

function evaluate(def: TrackDef): string {
  const t = buildTrack(def);
  const easy = autopilotLap(t, { aggression: 0.35, useBoost: false, useShortcut: false });
  const fast = autopilotLap(t, { aggression: 0.9, useBoost: true, useShortcut: false });
  const sc = autopilotLap(t, { aggression: 0.9, useBoost: true, useShortcut: true });
  const f = (s: { finished: boolean; time: number; collisions: number }) =>
    `${s.finished ? s.time.toFixed(1) + 's' : 'DNF'} (${s.collisions} col)`;
  return `${t.main.length.toFixed(0)} m | calmo ${f(easy)} | rápido ${f(fast)} | atalho ${f(sc)} | ganho ${(fast.time - sc.time).toFixed(2)}s`;
}

const [cmd, a, b] = process.argv.slice(2);
if (cmd === 'scan') {
  for (let seed = Number(a); seed <= Number(b); seed++) {
    const def = generateTrackDef(seed, { id: `seed-${seed}`, name: `Seed ${seed}`, theme: 'noturno' });
    console.log(`${seed}: ${def ? evaluate(def) : 'sem layout válido'}`);
  }
} else if (cmd === 'show') {
  const def = generateTrackDef(Number(a), { id: `seed-${a}`, name: `Seed ${a}`, theme: 'noturno' });
  console.log(def ? JSON.stringify(def, null, 2) : 'sem layout válido');
} else if (cmd === 'bake') {
  const defs: TrackDef[] = [];
  for (const m of MAP_SEEDS) {
    const def = generateTrackDef(m.seed, { id: m.id, name: m.name, theme: m.theme });
    if (!def) throw new Error(`seed ${m.seed} has no valid layout`);
    def.version = m.version;
    defs.push(def);
    console.log(`${m.name} (seed ${m.seed}): ${evaluate(def)}`);
  }
  const body = defs.map((d) => '  ' + JSON.stringify(d)).join(',\n');
  writeFileSync(
    new URL('../src/game/generatedMaps.ts', import.meta.url),
    `// Generated by \`npm run gen:maps\` from scripts/map-seeds.ts (see generator.ts).\n` +
      `// Do not edit by hand: change the seed list and regenerate.\n` +
      `import type { TrackDef } from './track';\n\n` +
      `export const GENERATED_MAPS: TrackDef[] = [\n${body},\n];\n`,
  );
  console.log('src/game/generatedMaps.ts escrito.');
} else {
  console.log('uso: gen:map -- scan <de> <até> | show <seed>   ·   gen:maps');
}
